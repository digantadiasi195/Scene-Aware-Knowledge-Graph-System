# Main
# ============================================================
if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--csv", required=True, help="Unified observation csv")
    parser.add_argument("--output", default="graph_dataset_20joints.pt", help="Output pt file")
    args = parser.parse_args()

    graphs = load_graph_dataset(args.csv)
    save_graph_dataset(graphs, args.output)